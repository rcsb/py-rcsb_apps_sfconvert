    def standardize_sg_name(self, symm, blkidx=0):
        """Standardize spacegroup name"""

        if symm is None:
            return None

        symm2 = symm.replace(" ", "")

        # Fix up some standard
        if symm2 == "R3:H":
            return "H3"
        if symm2 == "R33:H":
            return "H32"

        if symm2 == "P2":
            return "P 1 2 1"
        if symm2 == "P21":
            return "P 1 21 1"

        if symm2 == "C2":
            return "C 1 2 1"
        if symm2 == "C21":
            return "C 1 21 1"

        if symm2 == "I2":
            return "I 1 2 1"
        if symm2 == "I21":
            return "I 1 21 1"

        if symm2 == "A2":
            return "A 1 2 1"

        for s95 in self.__symmetry95:
            s95trim = s95.replace(" ", "")
            if s95trim == symm2:
                return s95

        self.__logger.pinfo(
            "Warning: the space group (%s) can not be converted to the standard" % symm, 0, block=blkidx
        )
        return symm

    def std_sgname(self, symm):
        if symm is None:
            return True

        for d in self.__stdsg:
            if symm == d["abbrev"] or symm == d["name"]:
                return True

        return False
